CLIENT_KEYS = ("open_menu", "close_menu", "collapse", "expand", "font_current", "error_ph", "required_choice", "invalid_choice")

def frontend_context():
    """Add display helpers without changing request parsing or engine results."""
    language = request.values.get("lang", "vi")
    if language not in ("vi", "en"):
        language = "vi"
    position = 0 if language == "vi" else 1

    def translate(key, **values):
        text = UI[key][position]
        return text.format(**values) if values else text

    def message(text):
        return translate_message(str(text), language)

    def source_label(url):
        labels = (
            ("power.larc.nasa.gov", "reference_nasa"),
            ("t0234e", "reference_salinity"),
            ("fao.org", "reference_rice"),
            ("irri.org", "reference_heat"),
            ("etccdi.pacificclimate.org", "reference_dry"),
            ("content.ces.ncsu.edu", "reference_sesame"),
            ("doi.org", "reference_rotation"),
        )
        return translate(next((key for domain, key in labels if domain in url), "sources"))

    return {
        "lang": language,
        "t": translate,
        "msg": message,
        "source_label": source_label,
        "client_messages": {key: translate(key) for key in CLIENT_KEYS},
    }
